"""app_tabs/predicao.py — Tela (Prediction): aplica um modelo `.joblib`
salvo a amostras novas. Extraído de app_quimiometria.py (item 18).
"""
from __future__ import annotations

import os
from typing import Callable, Dict, List

import pandas as pd
import streamlit as st

from guaraci.chemometric_stats import (
    FAIXA_NAO_DETECTAVEL,
    FAIXA_QUANTIFICADO,
    FAIXA_ZONA_CINZENTA,
)
from guaraci.predicao import (
    predict_samples as _predizer,
    predict_blind as _predizer_cego,
    anexar_colunas_fluxo_cego as _anexar_colunas_cego,
    validate_model_package as _validar_pacote_modelo,
    load_prediction_csv as _carregar_csv_predicao,
)
from guaraci import web_seguranca as _ws
from guaraci import model_export as _me


def render(upload_bloqueado: bool, tok: Callable[[], Dict[str, str]],
           T: Callable[[str], str] = lambda s: s) -> None:
    """Renderiza a aba Prediction.

    `upload_bloqueado` reflete GUARACI_DISABLE_MODEL_UPLOAD (mitigação de RCE
    via pickle em deploy público — ver comentário em app_quimiometria.py).
    Também esconde o campo de caminho local do CSV de predição quando ativo
    (achado S-NOVO-1 da auditoria de segurança de 2026-09-01): um campo de
    texto livre com caminho de servidor, num app público sem autenticação,
    deixa qualquer visitante ler qualquer arquivo de texto acessível ao
    processo, não só o operador que "sabe o caminho certo".

    `T`: traducao PT/EN (mesma funcao `_T` de app_quimiometria.py). Default
    no-op so' para chamada direta em teste isolado.
    """
    st.subheader(T("Prediction on Unknown Samples"))
    st.markdown(T(
        "Load a model generated by the pipeline and a CSV with new "
        "spectra (columns = wavenumbers, no class column)."
    ))

    col_m1, col_m2 = st.columns(2)
    with col_m1:
        if upload_bloqueado:
            # MODO SERVIDOR (padrao): so' o modelo PORTATIL em JSON -- um
            # arquivo de dados, que nao executa codigo ao ser lido. Nenhum
            # campo de caminho do servidor, nenhum .joblib (pickle).
            st.markdown(T("**1. Portable model (.json)**"))
            upld_jbl = st.file_uploader(
                T("Upload the portable model (.portatil.json)"),
                type=["json"], key="pred_model_upload_json")
            cam_jbl = ""
            confia_modelo = True   # JSON portatil nao executa codigo
            st.caption(T(
                "🔒 Online version: only the portable model (`modelo_plsda.portatil.json`, saved next to every trained model) is accepted, because it cannot run code. The full model (`.joblib`: blind flow, drift sentinel) needs the version installed on your own computer (`guaraci web`)."))
        else:
            st.markdown(T("**1. Trained model (.joblib)**"))
            st.caption(T(
                "⚠️ Only load `.joblib` models you generated yourself. "
                "A model file is a pickle and **runs code when loaded** — "
                "never load one from an untrusted source. The manifest "
                "signature is checked first; a model from another machine "
                "must be signed explicitly."))
            upld_jbl = None
            cam_jbl  = st.text_input(T("Local path to model"),
                                      key="pred_model_path",
                                      placeholder="C:/results/model_pls.joblib")
            confia_modelo = st.checkbox(
                T("I trust the source of this model file (required to load "
                "it — `.joblib` executes code when loaded, see "
                "`guaraci manual seguranca`)"),
                key="pred_model_confia", value=False)

    with col_m2:
        st.markdown(T("**2. New spectra (CSV)**"))
        upld_csv_pred = st.file_uploader(T("Upload CSV with new spectra"),
                                          type=["csv", "txt"],
                                          key="pred_csv_upload")
        if upload_bloqueado:
            st.caption(T("Do not upload personal or confidential data."))
            cam_csv_pred = ""
            st.caption(T(
                "🔒 Local path to CSV is disabled on this public "
                "deployment — a free-text server-side path would let any "
                "visitor read arbitrary files on the server. Use the "
                "upload above instead."))
        else:
            cam_csv_pred = st.text_input(T("Or local path to CSV"),
                                          key="pred_csv_path",
                                          placeholder="C:/data/new_spectra.csv")
        st.text_input(
            T("First column to use as wavenumber (leave empty = auto)"),
            key="pred_col_wn",
            placeholder="e.g.: 4000.0  (name or index of first spectral column)")

    # ---- Predict button -------------------------------------------------
    st.divider()
    if st.button(T("🔮 Predict"), type="primary", key="btn_predizer",
                 use_container_width=True):
        # R5-04: um novo clique NUNCA deixa a tabela/download da predicao
        # anterior na tela se a nova falhar (parecia resultado do arquivo novo).
        for _k in ("pred_resultados", "pred_resultados_cego"):
            st.session_state[_k] = None
        erros_pred: List[str] = []
        pkg_pred = None
        cam_modelo_efetivo: str = ""

        # Load model
        portatil = None   # modelo portatil (modo servidor)
        try:
            if upload_bloqueado:
                if upld_jbl is None:
                    erros_pred.append(T("No valid model provided (upload)."))
                else:
                    import json as _json
                    try:
                        dados_json = _json.loads(upld_jbl.getvalue().decode("utf-8"))
                    except (UnicodeDecodeError, _json.JSONDecodeError):
                        raise ValueError(T(
                            "The file is not a valid portable model (JSON)."))
                    if (not isinstance(dados_json, dict)
                            or dados_json.get("formato") != "guaraci-modelo-portatil"):
                        raise ValueError(T(
                            "The file is not a GUARACI portable model."))
                    portatil = dados_json
                    # R5-23: confirmar O QUE foi carregado.
                    st.caption(T("Model loaded: classes {cls}; spectral range {a:.0f}–{b:.0f}; applicability domain: {ad}.").format(
                        cls=", ".join(map(str, portatil.get("classes", []))),
                        a=float(portatil.get("wn_min", 0)), b=float(portatil.get("wn_max", 0)),
                        ad=T("yes") if portatil.get("dominio_aplicabilidade") else T("no (old file)")))
            elif not confia_modelo:
                erros_pred.append(T(
                    "Check 'I trust the source of this model file' above "
                    "before loading — required (see `guaraci manual seguranca`)."))
            elif cam_jbl and os.path.exists(cam_jbl):
                from guaraci.predicao import (
                    ModeloNaoAssinadoError, load_model as _load_model)
                try:
                    pkg_pred = _load_model(cam_jbl, confiar=True)
                except ModeloNaoAssinadoError as e_ass:
                    erros_pred.append(str(e_ass))
                cam_modelo_efetivo = cam_jbl
            # NOTE: this is STRUCTURE validation only — it runs AFTER the model
            # is loaded, so it does NOT prevent RCE from a malicious pickle
            # (the code already ran during load). The real barriers are the
            # confia_modelo checkbox (explicit human confirmation) and the
            # signed-manifest check inside load_model, which runs BEFORE
            # joblib.load and fails closed.
            if pkg_pred is not None:
                _validar_pacote_modelo(pkg_pred)
            elif portatil is None and not erros_pred:
                erros_pred.append(T("No valid model provided (upload or path)."))
        except Exception as e_jbl:  # noqa: BLE001 -- multi-etapa (leitura
            # do modelo + validacao de estrutura); erro exibido ao usuario.
            if upload_bloqueado:
                _msg, _ = _ws.mensagem_visitante(e_jbl, "leitura do modelo")
                erros_pred.append(_msg)
            else:
                erros_pred.append(T("Error loading model: {e}").format(e=e_jbl))

        # Load prediction CSV
        X_pred_raw = None
        wn_pred    = None
        try:
            fonte_csv = (upld_csv_pred if upld_csv_pred is not None
                         else cam_csv_pred if cam_csv_pred and os.path.exists(cam_csv_pred)
                         else None)
            if fonte_csv is None:
                erros_pred.append(T("No spectra CSV provided."))
            else:
                X_pred_raw, wn_pred, meta_pred = _carregar_csv_predicao(fonte_csv)
                st.session_state["pred_amostras"] = meta_pred
        except Exception as e_csv:  # noqa: BLE001 -- parsing defensivo de
            # CSV de amostra nova (formato variavel); erro exibido ao usuario.
            erros_pred.append(T("Error reading CSV: {e}").format(e=e_csv))

        if erros_pred:
            for e in erros_pred:
                st.error(e)
        elif portatil is not None and X_pred_raw is not None:
            try:
                with st.spinner(T("Applying model...")):
                    res = _me.predict_portable(portatil, X_pred_raw, wn_pred)
                    df_res = pd.DataFrame(res)
                    meta_df = st.session_state.get("pred_amostras")
                    if meta_df is not None and len(meta_df) == len(df_res):
                        from guaraci.predicao import anexar_metadados
                        df_res = anexar_metadados(meta_df, df_res)
                st.session_state["pred_resultados"] = df_res
                st.session_state["pred_resultados_cego"] = None
                st.session_state["pred_modelo_caminho"] = ""
                st.success(T("Prediction complete: {n} samples.").format(n=len(df_res)))
                if "AD_dentro_dominio" in df_res.columns:
                    _fora = int((~df_res["AD_dentro_dominio"].astype(bool)).sum())
                    if _fora:
                        st.warning(T("{n} sample(s) outside the model's applicability domain: the predicted class is not reliable for them.").format(n=_fora))
                else:
                    # R2-02: JSON antigo (formato 1) sem dominio de aplicabilidade.
                    st.warning(T("Portable model: no applicability-domain check. 'confidence' is a softmax score, not a calibrated probability, and is high even for spectra unlike the training data (noise, absent bands). Do not trust it for samples outside the training profile; use the local mode with the full model for a domain check."))
            except Exception as e_pred:  # noqa: BLE001 -- multi-etapa
                _msg, _ = _ws.mensagem_visitante(e_pred, "predição")
                st.error(_msg)
        else:       # sem erro e sem modelo portatil: ha' pacote .joblib e CSV (as duas faltas acima viram erro)
            try:
                with st.spinner(T("Applying model...")):
                    # Bloco 9b (D6, portado do CLI nesta rodada -- ver
                    # guaraci.py:_menu_prediction, mesma logica, zero
                    # duplicacao de calculo): quando o pacote traz o
                    # ensemble de identificacao, roda o fluxo completo
                    # Detectar->Identificar->Quantificar em vez do fluxo
                    # simples N1. Modelos exportados antes do Bloco 9b nao
                    # tem essa chave -- cai no caminho anterior, sem quebrar.
                    resultados_cego = None
                    if pkg_pred.get("identification_ensemble"):
                        df_res, resultados_cego = _predizer_cego(
                            pkg_pred, X_pred_raw, wn_pred)
                        _anexar_colunas_cego(df_res, resultados_cego)
                    else:
                        df_res = _predizer(pkg_pred, X_pred_raw, wn_pred)
                    # Re-attach metadata (sample names) if available
                    meta_df = st.session_state.get("pred_amostras")
                    if meta_df is not None and len(meta_df) == len(df_res):
                        df_res = pd.concat(
                            [meta_df.reset_index(drop=True), df_res], axis=1)
                st.session_state["pred_resultados"] = df_res
                st.session_state["pred_resultados_cego"] = resultados_cego
                st.session_state["pred_modelo_caminho"] = cam_modelo_efetivo
                st.success(T("Prediction complete: {n} samples.").format(n=len(df_res)))
            except Exception as e_pred:  # noqa: BLE001 -- multi-etapa
                # (predizer + concat de metadados); erro exibido ao usuario.
                st.error(T("Prediction error: {e}").format(e=e_pred))

    # ---- Results display ----------------------------------------
    df_show = st.session_state.get("pred_resultados")
    if df_show is not None:
        st.divider()
        st.markdown(T("**Prediction results**"))

        # Color accepted/rejected — via design tokens (contraste correto em
        # tema claro e escuro).
        _tkp = tok()
        def _colorir_aceito(val):
            if val is True:
                return (f"background-color:{_tkp['success_bg']};"
                        f" color:{_tkp['success']}")
            if val is False:
                return (f"background-color:{_tkp['error_bg']};"
                        f" color:{_tkp['error']}")
            return ""

        # Faixa de decisao (Bloco 24): mesmo tratamento visual dos booleanos
        # acima -- 3 estados, 3 cores do tema (nunca hex fixo).
        def _colorir_faixa(val):
            if val == FAIXA_NAO_DETECTAVEL:
                return f"background-color:{_tkp['error_bg']}; color:{_tkp['error']}"
            if val == FAIXA_ZONA_CINZENTA:
                return f"background-color:{_tkp['warn_bg']}; color:{_tkp['warn']}"
            if val == FAIXA_QUANTIFICADO:
                return (f"background-color:{_tkp['success_bg']};"
                        f" color:{_tkp['success']}")
            return ""

        cols_bool_colorir = [c for c in ("aceito", "AD_dentro_dominio")
                             if c in df_show.columns]
        if cols_bool_colorir or "faixa_decisao" in df_show.columns:
            _estilo = df_show.style
            if cols_bool_colorir:
                _estilo = _estilo.map(_colorir_aceito, subset=cols_bool_colorir)
            if "faixa_decisao" in df_show.columns:
                _estilo = _estilo.map(_colorir_faixa, subset=["faixa_decisao"])
            st.dataframe(_estilo, use_container_width=True)
        else:
            st.dataframe(df_show, use_container_width=True)

        # Download CSV
        csv_bytes = df_show.to_csv(index=False, sep=";", decimal=",").encode("utf-8")
        st.download_button(
            T("⬇️ Download results (.csv)"),
            data=csv_bytes,
            file_name="predicao_resultados.csv",
            mime="text/csv",
            use_container_width=True,
        )

        # Quick summary
        col_m1, col_m2 = st.columns(2)
        if "aceito" in df_show.columns:
            n_ac = int(df_show["aceito"].sum())
            n_tot = len(df_show)
            with col_m1:
                st.metric(T("Within PLS-DA model fit"), f"{n_ac} / {n_tot}",
                          delta=f"{n_ac/n_tot*100:.1f}%")
                st.caption(T(
                    "Combined distance of Hotelling T² (distance along the "
                    "model's main directions) and Q-residual (unexplained "
                    "variation) within the 95% limit — see the 'criterio' "
                    "column for the exact rule applied; the T2_ok and Q_ok "
                    "columns are per-axis diagnostics only. A sample "
                    "outside this fit is an atypical spectrum for the "
                    "calibration, not necessarily 'adulterated'."))
                if "confianca_%" in df_show.columns:
                    st.caption(T(
                        "'confianca_%' is a relative score (normalized "
                        "PLS-DA), not a calibrated probability."))
        # Applicability Domain (PCA-based, Jaworska et al. 2005) — only
        # present if the .joblib package carries the AD artifacts (pipeline
        # versions exporting pca/ad_var_t/ad_t2_limite/ad_q_limite).
        if "AD_dentro_dominio" in df_show.columns:
            n_ad = int(df_show["AD_dentro_dominio"].sum())
            n_tot = len(df_show)
            with col_m2:
                st.metric(T("Within applicability domain"), f"{n_ad} / {n_tot}",
                          delta=f"{n_ad/n_tot*100:.1f}%")
                st.caption(T(
                    "Exploratory PCA check (Hotelling T²/Q-residual, "
                    "Jaworska et al. 2005) of similarity to the training "
                    "set as a whole — a broader, less strict screen than "
                    "the PLS-DA fit above. 'Outside' flags a spectrum "
                    "unlike anything the model was calibrated on."))
                _ncv = (int(df_show["AD_ref_cv_n"].iloc[0])
                        if "AD_ref_cv_n" in df_show.columns and len(df_show)
                        else 0)
                if _ncv > 0:
                    _taxa = int(df_show["AD_ref_cv_rejeitadas"].iloc[0]) / _ncv
                    st.caption(T(
                        "Expected alarm rate on legitimate samples "
                        "(cross-validated rejection of the calibration): "
                        "{taxa} (nominal 5%). With few physical samples per "
                        "class it can be much higher.").format(
                            taxa=f"{_taxa:.1%}"))

            # Bloco 13b: sentinela de deriva -- MESMA logica do menu do
            # CLI (`guaraci.py`, `sentinela_deriva.hook_apos_predicao`),
            # nunca duplicada. Fica sob este `if` (depende de
            # AD_dentro_dominio), nao do fluxo cego abaixo.
            cam_modelo_sent = st.session_state.get("pred_modelo_caminho")
            if cam_modelo_sent:
                try:
                    import guaraci.sentinela_deriva as _sent
                    alerta_sent = _sent.hook_apos_predicao(
                        cam_modelo_sent, df_show)
                    if alerta_sent is not None:
                        _msg_sent = T("🛰 Drift sentinel (n={n}): {msg}").format(
                            n=alerta_sent.n, msg=alerta_sent.mensagem)
                        st.warning(_msg_sent) if alerta_sent.alerta \
                            else st.caption(_msg_sent)
                except Exception as _e_sent:  # noqa: BLE001 -- diagnostico
                    # opcional; nao afeta a predicao ja exibida.
                    st.caption(T("Drift sentinel unavailable: {e}").format(
                        e=_e_sent))

        # Conjunto de predicao conforme p/ classificacao (Grupo 2, analogo
        # classificatorio do T1 de regressao) -- so' presente se o pacote
        # foi salvo por uma versao do pipeline que calibrou no holdout.
        if "classes_plausiveis" in df_show.columns:
            cobertura_col = df_show.get("conjunto_cobertura_nominal")
            cobertura = (cobertura_col.iloc[0]
                         if cobertura_col is not None and len(cobertura_col) else None)
            if cobertura is not None:
                n_ambig = int(df_show["classes_plausiveis"].str.contains(
                    r"\|", regex=True).sum())
                n_vazio = int((df_show["classes_plausiveis"] == "").sum())
                st.caption(T(
                    "🎯 Plausible class set (conformal, {cov:.0%} coverage): "
                    "{amb} sample(s) with more than 1 plausible class, "
                    "{vaz} with none — see 'classes_plausiveis' column."
                ).format(cov=float(cobertura), amb=n_ambig, vaz=n_vazio))
            else:
                st.caption(T(
                    "🎯 Plausible class set: NOT VALIDATED (holdout lacked "
                    "enough independent groups for alpha=0.05)."))

        # Bloco 9b -- Fluxo cego (Detectar->Identificar->Quantificar).
        # Mesmos numeros/regras do resumo do CLI (_menu_prediction), so'
        # apresentado como metricas Streamlit em vez de texto Rich.
        resultados_cego = st.session_state.get("pred_resultados_cego")
        if "classe_identificada" in df_show.columns and resultados_cego:
            st.divider()
            st.markdown(T("**Blind flow — Detect → Identify → Quantify**"))
            n_tot = len(df_show)
            n_pura = sum(1 for r in resultados_cego if r.pureza.aceito is True)
            n_adulterada = sum(1 for r in resultados_cego if r.pureza.aceito is False)
            n_identificado = sum(
                1 for r in resultados_cego
                if r.identificacao.classe_identificada is not None)
            n_quantificado = sum(
                1 for r in resultados_cego
                if r.quantificacao.teor_estimado is not None)

            col_c1, col_c2, col_c3 = st.columns(3)
            with col_c1:
                st.metric(T("🧪 Purity (predicted species)"),
                          f"{n_pura} / {n_tot}",
                          delta=T("pure"))
                st.caption(T(
                    "DD-SIMCA for the species predicted above. "
                    "{n} detected as adulterated.").format(n=n_adulterada))
            with col_c2:
                st.metric(T("🏷 Adulterant identified"),
                          f"{n_identificado} / {n_tot}")
                st.caption(T(
                    "UNKNOWN means no species×adulterant combination had a "
                    "statistical guarantee both sufficient AND exclusive "
                    "for this sample — either no guarantee, or 2+ "
                    "validated combinations tied (also blocks the label)."))
            with col_c3:
                st.metric(T("⚖ Quantified"), f"{n_quantificado} / {n_tot}")
                st.caption(T(
                    "Blocked = quantification refused because the "
                    "adulterant was not reliably identified — see "
                    "'quantificacao_motivo_bloqueio' in the table above."))
            # ── Faixa de decisao (Bloco 24) — 3 estados ────────────────
            # Reaproveita `r.quantificacao.faixa_decisao`, ja calculado
            # contra o LOD/LOQ do Bloco 12 (mesmos numeros da CLI, ver
            # guaraci.py:_menu_prediction). Nada e' recalculado aqui.
            _n_nao_det = sum(1 for r in resultados_cego
                             if r.quantificacao.faixa_decisao == FAIXA_NAO_DETECTAVEL)
            _n_cinza = sum(1 for r in resultados_cego
                           if r.quantificacao.faixa_decisao == FAIXA_ZONA_CINZENTA)
            _n_conf = sum(1 for r in resultados_cego
                          if r.quantificacao.faixa_decisao == FAIXA_QUANTIFICADO)
            _n_com_faixa = _n_nao_det + _n_cinza + _n_conf

            st.markdown(T("**Decision range (LOD / LOQ)**"))
            if _n_com_faixa == 0:
                # Nunca mostra "0 abaixo do LOD" como se fosse resultado: sem
                # LOD/LOQ persistido nao ha' faixa nenhuma a declarar.
                st.info(T(
                    "No LOD/LOQ available for the species models used — either "
                    "the package predates the decision-range feature, or the "
                    "limits are not computable (not enough physical replicates "
                    "to estimate instrument noise). No decision range is shown "
                    "rather than one without backing."))
            else:
                for _rot, _n, _ajuda in (
                    (T("Below LOD (not detectable)"), _n_nao_det,
                     T("Estimated content below the detection limit — the "
                       "method cannot distinguish it from noise.")),
                    (T("Grey zone (LOD–LOQ)"), _n_cinza,
                     T("Detection is possible, but quantification is not "
                       "reliable in this range — report as 'detected, not "
                       "quantifiable'.")),
                    (T("Quantified with confidence (≥ LOQ)"), _n_conf,
                     T("At or above the quantification limit — the numeric "
                       "value can be reported as a measurement.")),
                ):
                    st.progress(_n / _n_com_faixa,
                                text=f"{_rot} — {_n}/{_n_com_faixa}")
                    st.caption(_ajuda)
                if n_quantificado > _n_com_faixa:
                    st.caption(T(
                        "{n} quantified sample(s) have no decision range: the "
                        "species model used has no persisted LOD/LOQ.").format(
                            n=n_quantificado - _n_com_faixa))
                st.caption(T(
                    "Limits from the analytical figures of merit of the "
                    "per-species regression (Valderrama, Braga & Poppi 2009), "
                    "computed during the run — see `lod`/`loq` in the table "
                    "above."))

            st.warning(T(
                "⚠ 'classe_identificada' only ever exists when "
                "'identificacao_cobertura'='validado' (formal statistical "
                "guarantee, calibrated with ≥2 independent collection "
                "sessions) — there is no 'informational' label without "
                "that guarantee. 'identificacao_candidatos' carries only "
                "the closest guess (with NO guarantee at all) for "
                "reference, never as a result to act on for a quality "
                "decision without confirming by a reference method."))
