def legenda_figura(nome_arquivo: str, pt: bool) -> str:
    """Descricao legivel da figura (legenda e texto alternativo)."""
    base = nome_arquivo.lower()
    for chave, (t_pt, t_en) in _LEGENDAS_FIG:
        if chave in base:
            return t_pt if pt else t_en
    return nome_arquivo


def render(T: Callable[[str], str], tok: Callable[[], Dict[str, str]],
           load_summary: Callable[[str], str], list_figures: Callable[[str], list]) -> None:
    """Renderiza a aba Validation. `load_summary`/`list_figures` são as
    versões cacheadas (@st.cache_data) definidas em app_quimiometria.py."""
    st.subheader(T("Validation Results"))
    st.caption("📊 Figures and metrics generated by the last pipeline run "
               "(Model tab).")
    pasta_v = st.session_state.get("ultima_pasta")

    if not pasta_v or not os.path.isdir(pasta_v):
        st.info(T("No results yet. Run the pipeline in the Model tab."))
        return

    st.caption(f"Folder: `{os.path.abspath(pasta_v)}`")

    # Numeric summary
    resumo_txt = load_summary(pasta_v)          # chaves fixas: so' para extrair numeros
    from guaraci.app_logic import load_summary_text
    exibir = load_summary_text(pasta_v) or resumo_txt   # o .txt no idioma da execucao
    if exibir:
        with st.expander(T("📋 Model summary (resumo_modelo.txt)"), expanded=True):
            # Split into main section and notes section for cleaner display
            marca = next((m for m in ("Methodological Notes", "Notas metodologicas") if m in exibir), None)
            if marca:
                notes_part = exibir[exibir.find(marca):].strip()
                main_part = exibir[:exibir.find(marca)].rstrip().rstrip("-").strip()
                st.code(main_part, language="text")
                with st.expander(T("📋 Methodological Notes (for peer review)"), expanded=False):
                    st.code(notes_part, language="text")
            else:
                st.code(exibir, language="text")

    # ── Per-Class Accuracy table (extracted from summary) ───────────────
    if resumo_txt:
        acc_map = parse_accuracy_by_class(resumo_txt)
        if acc_map:
            with st.expander(T("📊 Accuracy by Class"), expanded=True):
                _df_acc = pd.DataFrame(
                    list(acc_map.items()), columns=["Class", "Accuracy (recall)"]
                ).sort_values("Accuracy (recall)")
                # Color: red < 0.7, yellow 0.7-0.9, green >= 0.9
                # Cores vindas dos design tokens do tema ativo → contraste
                # correto em claro E escuro (não mais hex claros fixos).
                _tkc = tok()
                def _cor_acc(v: object) -> str:  # Scalar compat
                    fv = float(v)  # type: ignore[arg-type]    # a coluna so' traz acuracias numericas (parse_accuracy_by_class)
                    if fv >= 0.90:
                        return (f"background-color:{_tkc['success_bg']};"
                                f"color:{_tkc['success']}")
                    if fv >= 0.70:
                        return (f"background-color:{_tkc['warn_bg']};"
                                f"color:{_tkc['warn']}")
                    return (f"background-color:{_tkc['error_bg']};"
                            f"color:{_tkc['error']}")
                st.dataframe(
                    _df_acc.style.map(
                        _cor_acc, subset=["Accuracy (recall)"]),
                    use_container_width=True, height=min(400, 35 * len(_df_acc) + 38))

    # ── Benchmark and MC CV tables (if they exist) ───────────────────
    _bench_csv_v = os.path.join(pasta_execucao(pasta_v, NOME_TABELAS),
                                "benchmark_classifiers.csv")
    _mc_csv_v    = os.path.join(pasta_execucao(pasta_v, NOME_TABELAS), "monte_carlo_cv.csv")
    if os.path.exists(_bench_csv_v) or os.path.exists(_mc_csv_v):
        with st.expander(T("🏅 Classifier Benchmark"), expanded=False):
            if os.path.exists(_bench_csv_v):
                try:
                    _df_b = pd.read_csv(_bench_csv_v, sep=";", decimal=",")
                    st.markdown(T("**Auto-Benchmark — Balanced Accuracy by model (GroupKFold)**"))
                    st.dataframe(_df_b, use_container_width=True)
                except (pd.errors.ParserError, OSError, UnicodeDecodeError) as _e_b:
                    st.warning(f"Error reading benchmark CSV: {_ws.msg_segura(_e_b)}")
            if os.path.exists(_mc_csv_v):
                try:
                    _df_mc = pd.read_csv(_mc_csv_v, sep=";", decimal=",")
                    st.markdown(T("**Monte Carlo CV — 95% CI by percentile**"))
                    st.dataframe(_df_mc, use_container_width=True)
                except (pd.errors.ParserError, OSError, UnicodeDecodeError) as _e_mc:
                    st.warning(f"Error reading MC CV CSV: {_ws.msg_segura(_e_mc)}")

    # Gallery filtered by figure category
    imgs_v = list_figures(pasta_v)
    if imgs_v:
        st.markdown(f"**{len(imgs_v)} figures generated**")
        filtro_v = st.selectbox(
            T("Filter by category"), list(_CATS.keys()), key="filtro_valid",
            help="Show only figures of one analysis type (e.g. PCA scores, "
                 "confusion matrix, DD-SIMCA acceptance). 'All' shows every "
                 "figure generated by the run.")
        token_v  = _CATS[filtro_v].lower()
        imgs_filt = [im for im in imgs_v
                     if token_v in os.path.basename(im).lower()] \
                    if token_v else imgs_v

        if imgs_filt:
            cols_v = st.columns(2)
            for j, img in enumerate(imgs_filt):
                with cols_v[j % 2]:
                    st.image(img, caption=legenda_figura(
                                 os.path.basename(img),
                                 st.session_state.get("lang") == "PT"),
                             use_container_width=True)
        else:
            st.info(T("No figures found for '{f}'.").format(f=filtro_v))
    else:
        st.info(T("Figures saved in non-displayable format (PDF/SVG). "
                  "Use the download button in the Reports tab."))
